def seed_database(conn: sqlite3.Connection, force_reset: bool = False) -> None:
    """
    Seeds the SQLite database with initial synthetic cases, dynamic alerts, and audit logs.
    Safe startup behavior: When force_reset is False (normal application startup), existing cases,
    user modifications, EVC updates, officer decisions, and audit logs are NEVER overwritten or duplicated.
    """
    cursor = conn.cursor()

    if force_reset:
        cursor.execute("DELETE FROM cases")
        cursor.execute("DELETE FROM alerts")
        cursor.execute("DELETE FROM audit_logs")

    cursor.execute("SELECT COUNT(*) as cnt FROM cases")
    if cursor.fetchone()["cnt"] == 0:
        initial_cases = get_initial_cases(include_drafts=True)
        for c in initial_cases:
            cursor.execute(
                """
                INSERT INTO cases (
                    application_id, institution_name, state, city, application_type,
                    programme, proposed_intake, submission_date, current_stage,
                    compliance_status, assigned_officer, assigned_role, sla_deadline,
                    evc_required, evc_due, extracted_fields_json, documents_json,
                    compliance_results_json, evc_inspection_json, decisions_json, updated_at
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                """,
                (
                    c["application_id"],
                    c["institution_name"],
                    c["state"],
                    c["city"],
                    c["application_type"],
                    c["programme"],
                    c["proposed_intake"],
                    c["submission_date"],
                    c["current_stage"],
                    c["compliance_status"],
                    c["assigned_officer"],
                    c["assigned_role"],
                    c["sla_deadline"],
                    1 if c["evc_required"] else 0,
                    1 if c["evc_due"] else 0,
                    json.dumps(c["extracted_fields"]),
                    json.dumps(c["documents"]),
                    json.dumps(c["compliance_results"]),
                    json.dumps(c["evc_inspection"]),
                    json.dumps(c["decisions"]),
                    c["updated_at"],
                ),
            )

        dynamic_alerts = compute_dynamic_alerts_from_cases(initial_cases)
        for a in dynamic_alerts:
            cursor.execute(
                """
                INSERT INTO alerts (
                    id, application_id, institution_name, severity, category,
                    title, message, due_date, escalation_status, recommended_action, created_at
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                """,
                (
                    a["id"],
                    a["application_id"],
                    a["institution_name"],
                    a["severity"],
                    a["category"],
                    a["title"],
                    a["message"],
                    a["due_date"],
                    a["escalation_status"],
                    a["recommended_action"],
                    a["created_at"],
                ),
            )

    cursor.execute("SELECT COUNT(*) as cnt FROM audit_logs")
    if cursor.fetchone()["cnt"] == 0:
        for log in get_initial_audit_logs():
            cursor.execute(
                """
                INSERT INTO audit_logs (
                    id, application_id, timestamp, actor_name, actor_role,
                    action_type, previous_value, new_value, remarks
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
                """,
                (
                    log["id"],
                    log["application_id"],
                    log["timestamp"],
                    log["actor_name"],
                    log["actor_role"],
                    log["action_type"],
                    log["previous_value"],
                    log["new_value"],
                    log["remarks"],
                ),
            )
