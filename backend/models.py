def compute_dynamic_alerts_from_cases(cases: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """
    Computes in-app compliance, document, SLA, and EVC alerts dynamically from actual persisted case state.
    Every alert is explicitly tagged as notification_type='IN_APP_NOTIFICATION'.
    """
    alerts: List[Dict[str, Any]] = []
    idx = 1

    for c in cases:
        if c.get("current_stage") == "Draft":
            continue
        app_id = c["application_id"]
        inst = c["institution_name"]
        deadline = c["sla_deadline"]
        stage = c["current_stage"]
        rules = c.get("compliance_results", [])
        docs = c.get("documents", [])
        evc = c.get("evc_inspection", {}) or {}

        # 1. Check for failed compliance rules / missing mandatory fields
        failed_rules = [r for r in rules if r.get("status") in ("Fail", "FAILED")]
        if failed_rules:
            r0 = failed_rules[0]
            alerts.append(
                {
                    "id": f"ALT-2026-{idx:02d}",
                    "alert_id": f"ALT-2026-{idx:02d}",
                    "application_id": app_id,
                    "case_id": app_id,
                    "institution_name": inst,
                    "severity": "HIGH",
                    "category": "COMPLIANCE",
                    "title": f"{r0.get('rule_name', 'Compliance Failure')} — {r0.get('explanation', '')}",
                    "message": f"{r0.get('explanation', '')} [Page {r0.get('evidence_page', 1)}]. Stage: {stage}.",
                    "due_date": deadline,
                    "status": "OPEN",
                    "escalation_status": "Escalated to Reviewing Officer — Deficiency Active",
                    "recommended_action": r0.get("corrective_action", "Inspect document and issue Clarification Notice."),
                    "notification_type": "IN_APP_NOTIFICATION",
                    "created_at": c.get("updated_at", "2026-10-26 09:15:00 UTC"),
                }
            )
            idx += 1

        # 2. Check for unverified or missing-field documents
        missing_docs = [
            d for d in docs if d.get("status") in ("Missing Field", "MISSING", "Pending Scrutiny", "PENDING_VERIFICATION")
        ]
        if missing_docs and not failed_rules:
            d0 = missing_docs[0]
            alerts.append(
                {
                    "id": f"ALT-2026-{idx:02d}",
                    "alert_id": f"ALT-2026-{idx:02d}",
                    "application_id": app_id,
                    "case_id": app_id,
                    "institution_name": inst,
                    "severity": "HIGH",
                    "category": "DOCUMENT",
                    "title": f"Deficient Annexure: {d0.get('title')}",
                    "message": d0.get("notes") or "Mandatory annexure requires officer verification or replacement upload.",
                    "due_date": deadline,
                    "status": "OPEN",
                    "escalation_status": "SLA Breach Risk — Scrutiny Hold",
                    "recommended_action": "Verify annexure in Document Verification or record deficiency.",
                    "notification_type": "IN_APP_NOTIFICATION",
                    "created_at": c.get("updated_at", "2026-10-26 09:15:00 UTC"),
                }
            )
            idx += 1

        # 3. Check for EVC due / EVC observations
        if c.get("evc_required") and evc.get("visit_status") not in ("Completed", "Completed - Clear"):
            v_status = evc.get("visit_status", "Not Scheduled")
            sev = "HIGH" if v_status in ("Not Scheduled", "Pending Schedule") else "MEDIUM"
            sched = evc.get("scheduled_date") or evc.get("proposed_date") or deadline
            alerts.append(
                {
                    "id": f"ALT-2026-{idx:02d}",
                    "alert_id": f"ALT-2026-{idx:02d}",
                    "application_id": app_id,
                    "case_id": app_id,
                    "institution_name": inst,
                    "severity": sev,
                    "category": "EVC",
                    "title": f"EVC Inspection {v_status} ({sched}) — {evc.get('recommendation') or evc.get('next_action') or 'Verify field readiness'}",
                    "message": f"{evc.get('observations', '')} | Report Status: {evc.get('report_uploaded', 'Pending Visit')}.",
                    "due_date": sched if sched not in ("N/A", "") else deadline,
                    "status": "OPEN",
                    "escalation_status": f"Assigned to {evc.get('committee_chair', 'EVC Committee')}",
                    "recommended_action": evc.get("recommendation", "Complete EVC inspection and verify report."),
                    "notification_type": "IN_APP_NOTIFICATION",
                    "created_at": evc.get("updated_at") or c.get("updated_at", "2026-10-25 17:40:00 UTC"),
                }
            )
            idx += 1

        # 4. Check for Human Review Required rules (e.g., Faculty Cadre)
        review_rules = [
            r
            for r in rules
            if r.get("status") in ("Requires Human Review", "Warning", "WARNING")
            and r.get("rule_id") == "PROTOTYPE-RULE-FAC-03"
        ]
        if review_rules and not failed_rules:
            rr = review_rules[0]
            alerts.append(
                {
                    "id": f"ALT-2026-{idx:02d}",
                    "alert_id": f"ALT-2026-{idx:02d}",
                    "application_id": app_id,
                    "case_id": app_id,
                    "institution_name": inst,
                    "severity": "MEDIUM",
                    "category": "DEADLINE",
                    "title": f"Human Review Required: {rr.get('rule_name')}",
                    "message": f"{rr.get('explanation')} (SLA Deadline: {deadline}).",
                    "due_date": deadline,
                    "status": "OPEN",
                    "escalation_status": f"Assigned to {c.get('assigned_officer', 'Reviewing Officer')}",
                    "recommended_action": rr.get("corrective_action", "Review faculty roster and record officer decision."),
                    "notification_type": "IN_APP_NOTIFICATION",
                    "created_at": c.get("updated_at", "2026-10-25 17:40:00 UTC"),
                }
            )
            idx += 1

    return alerts


